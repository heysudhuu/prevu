import { CbtQuestion } from '../types'

const LETTERS = ['A', 'B', 'C', 'D'] as const

function q(
  num: number,
  topic: string,
  topicName: string,
  sectionName: string,
  question: string,
  correctText: string,
  d1: string,
  d2: string,
  d3: string,
  explanation: string,
  passage?: string,
  difficulty: 'easy' | 'medium' = 'easy'
): CbtQuestion {
  const slot = (num - 1) % 4
  const distractors = [d1, d2, d3]
  const orderedTexts: string[] = []
  let dIdx = 0
  for (let i = 0; i < 4; i++) {
    if (i === slot) {
      orderedTexts.push(correctText)
    } else {
      orderedTexts.push(distractors[dIdx++])
    }
  }
  return {
    id: `ent-s1-q${num}`,
    subjectCode: 'ENT-101',
    subjectName: 'Entrepreneurship Mindset',
    semester: 1,
    category: 'core',
    topic,
    topicName,
    partName: 'Set 1: Corrected Practice Sample Paper',
    sectionName,
    ...(passage ? { passage } : {}),
    question,
    type: 'single',
    options: orderedTexts.map((text, idx) => ({ id: LETTERS[idx], text })),
    correctAnswers: [LETTERS[slot]],
    explanation,
    difficulty
  }
}

